"""Builds mobile/web/js/locales.js: the phone app's translations, taken from the desktop catalogs.

The phone app uses the same convention as the desktop: the English text is the key. Every `t('…')` in
mobile/web/js is looked up in src/i18n/locales/<code>.json; text only the phone shows lives in
mobile/i18n/phone.json ({"es": {"English": "Español"}, ...}). Labels the server sends in English (form status,
load levels, window names...) are listed here from their source, so they are translated too.

    python -m mobile.build_locales            write js/locales.js
    python -m mobile.build_locales --check    fail if it is out of date or a string has no translation
"""
import json
import re
import sys
from pathlib import Path

from src.i18n import catalog

HERE = Path(__file__).parent
JS_DIR = HERE / "web" / "js"
PHONE = HERE / "i18n" / "phone.json"
OUT = JS_DIR / "locales.js"
LANGUAGES = ("es", "ca")

_CALL = re.compile(r"""\bt\(\s*(?P<q>['"`])(?P<s>(?:\\.|(?!(?P=q)).)*)(?P=q)""", re.S)
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def _unescape(s):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


def used_in_code():
    found = set()
    for path in sorted(JS_DIR.glob("*.js")):
        if path.name == "locales.js":
            continue
        found.update(_unescape(m.group("s")) for m in _CALL.finditer(path.read_text(encoding="utf-8")))
    return found


def sent_by_server():
    """English labels the API returns (the phone passes them to t())."""
    from src.analysis import labels, nutrition, power_profile as pp
    out = set(nutrition.LOADS.values()) | set(nutrition.INTAKES.values()) | set(pp.PROFILE_DURATIONS)
    out |= {"Last 42 days", "Last 90 days", "All time"}
    for fn, samples in ((labels.ramp_status, (10, 5, 0, -5)), (labels.acwr_status, (0.5, 1.0, 1.4, 2.0)),
                        (labels.form_status, (30, 10, 0, -20, -40)), (labels.monotony_status, (3.0, 1.0))):
        out |= {fn(v) for v in samples}
    out |= {"Rides", "Training", "Power"}                       # tab labels, passed as variables
    return {s for s in out if s}


def wanted():
    return sorted(used_in_code() | sent_by_server())


def translations(code, keys):
    desktop = {k: v for k, v in catalog.strings(code).items() if isinstance(v, str) and v}
    phone = json.loads(PHONE.read_text(encoding="utf-8")).get(code, {}) if PHONE.exists() else {}
    out, missing = {}, []
    for k in keys:
        v = phone.get(k) or desktop.get(k)
        if not v:
            missing.append(k)
        elif v != k:
            out[k] = v
    return out, missing


def problems(keys=None):
    """(placeholder mismatches, untranslated) for every language."""
    keys = keys or wanted()
    bad, missing = [], {}
    for code in LANGUAGES:
        out, miss = translations(code, keys)
        missing[code] = miss
        for k, v in out.items():
            if set(PLACEHOLDER.findall(k)) != set(PLACEHOLDER.findall(v)):
                bad.append((code, k))
    return bad, missing


def render():
    keys = wanted()
    body = {code: translations(code, keys)[0] for code in LANGUAGES}
    lines = ["// Generated by `python -m mobile.build_locales`: do not edit by hand.",
             "export const LOCALES = " + json.dumps(body, ensure_ascii=False, indent=1, sort_keys=True) + ";", ""]
    return "\n".join(lines)


def main(argv=None):
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    bad, missing = problems()
    for code, k in bad:
        print(f"[{code}] placeholders differ: {k!r}")
    for code, ks in missing.items():
        for k in ks:
            print(f"[{code}] no translation: {k!r}")
    text = render()
    if check:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        if stale:
            print("mobile/web/js/locales.js is out of date: run python -m mobile.build_locales")
        return 1 if (stale or bad or any(missing.values())) else 0
    OUT.write_text(text, encoding="utf-8")
    entries = sum(len(v) for v in json.loads(text.split("=", 1)[1].strip().rstrip(";")).values())
    print(f"wrote {OUT} ({entries} entries)")
    return 1 if (bad or any(missing.values())) else 0


if __name__ == "__main__":
    sys.exit(main())
